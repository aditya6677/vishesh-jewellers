'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { randomBytes, randomUUID } = require('node:crypto');
const { openDatabase: openOperationalDatabase } = require('../lib/database/database');
const openDatabase = (file, key) => openOperationalDatabase(file, key, { create: !fs.existsSync(file) });
const { importSnapshot, readSnapshot } = require('../lib/database/snapshot-migration');
const { InvoiceRepository } = require('../lib/database/invoice-repository');
const { createInvoice } = require('../lib/services/invoice-creation');
const { editInvoice } = require('../lib/services/invoice-editing');
const { voidInvoice } = require('../lib/services/invoice-voiding');
const { deleteInvoice } = require('../lib/delete-invoice');
const { RecordService } = require('../lib/services/record-service');

test('database editing, pending delivery, void and deletion match existing reversal rules atomically', t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'vj-invoice-lifecycle-repo-'));
  const key = randomBytes(32), file = path.join(directory, 'lifecycle.db');
  let db = openDatabase(file, key);
  t.after(() => { if (db.open) db.close(); key.fill(0); fs.rmSync(directory, { recursive: true, force: true }); });
  let memory = { 'stock-list': [{ id: 'ring', item: 'Gold Ring', purity: '22K', qty: 10, gross: 100, net: 90 }], 'invoice-records': [], 'old-gold-records': [], 'purchase-records': [], 'payment-records': [], 'invoice-counter': 1 };
  importSnapshot(db, memory, { storeId: 'a', sourceSha256: 'a'.repeat(64), acknowledgeLegacy: true });
  const now = () => new Date('2026-10-28T08:00:00Z'), dependencies = { now, id: () => 'settle-fixed' };
  const repo = new InvoiceRepository(db, 'a', dependencies);
  const store = { read: () => structuredClone(memory), write: data => { memory = structuredClone(data); } };
  const records = new RecordService(store, dependencies);
  const line = { stockId: 'ring', name: 'Gold Ring', purity: '22K', pcs: 4, gross: 10, net: 9, rate: 1000, making: 0 };
  const sale = { requestId: randomUUID(), number: 'VJ000001', status: 'completed', customer: 'Synthetic lifecycle', invoiceDate: '2026-10-28', items: [line], exchanges: [{ metal: 'gold', weight: .1, rate: 1000 }], manualDiscount: 20, gstRate: 3, paid: 1000, expectedTotal: 9150 };
  repo.create(sale); createInvoice(store, sale, now);
  const settlement = { version: repo.get(sale.number).version, method: 'silver', weight: 2, rate: 50 };
  repo.settle(sale.number, settlement); records.settle(sale.number, settlement);
  const edit = { version: repo.get(sale.number).version, customer: sale.customer, invoiceDate: sale.invoiceDate, items: [{ ...line, pcs: 5, gross: 20, net: 18 }], exchanges: [{ metal: 'gold', weight: .2, rate: 1000 }], manualDiscount: 40, gstRate: 3, paid: 1500, expectedTotal: 18300 };
  const before = readSnapshot(db, 'a');
  db.exec("CREATE TRIGGER reject_lifecycle_receipt BEFORE INSERT ON documents WHEN NEW.collection='old-gold-records' BEGIN SELECT RAISE(ABORT,'receipt failure'); END;");
  assert.throws(() => repo.edit(sale.number, edit), /receipt failure/);
  assert.deepEqual(readSnapshot(db, 'a'), before);
  db.exec('DROP TRIGGER reject_lifecycle_receipt');
  assert.deepEqual(repo.edit(sale.number, edit).record, editInvoice(store, sale.number, edit, now).record);
  assert.deepEqual(readSnapshot(db, 'a'), memory);
  assert.throws(() => repo.edit(sale.number, edit), /changed/);
  const pending = { ...sale, number: 'VJ000002', requestId: randomUUID(), status: 'pending', exchanges: [], manualDiscount: 0, expectedTotal: 9270, paid: 100 };
  repo.create(pending); createInvoice(store, pending, now);
  const delivery = { ...edit, version: repo.get(pending.number).version, items: [{ ...line, pcs: 1, gross: 5, net: 4 }], exchanges: [], manualDiscount: 0, expectedTotal: 4120, paid: 100 };
  assert.deepEqual(repo.edit(pending.number, delivery).record, editInvoice(store, pending.number, delivery, now).record);
  assert.deepEqual(readSnapshot(db, 'a'), memory);
  assert.equal(repo.get(pending.number).record.status, 'completed');
  assert.equal(repo.get(pending.number).record.deliveredAt, now().toISOString());
  const reason = { version: repo.get(sale.number).version, reason: 'Synthetic cancellation' };
  const unspent = structuredClone(memory);
  const spending = { sourceId: 'synthetic-party-metal', invoice: '—', metal: 'gold', source: 'Metal payment', weight: -.2, value: 0, rate: 0 };
  const spendingOrdinal = db.prepare("SELECT min(ordinal)-1 AS n FROM documents WHERE store_id='a' AND collection='old-gold-records'").get().n;
  db.prepare("INSERT INTO documents VALUES('a','old-gold-records',?,NULL,?)").run(spendingOrdinal, JSON.stringify(spending));
  memory['old-gold-records'].unshift(spending);
  assert.throws(() => repo.void(sale.number, reason), /already been used/);
  assert.throws(() => repo.delete(sale.number), /already been used/);
  assert.deepEqual(readSnapshot(db, 'a'), memory);
  db.prepare("DELETE FROM documents WHERE store_id='a' AND collection='old-gold-records' AND ordinal=?").run(spendingOrdinal);
  memory = unspent;
  db.exec("CREATE TRIGGER reject_void BEFORE INSERT ON documents WHEN NEW.collection='old-gold-records' BEGIN SELECT RAISE(ABORT,'void failure'); END;");
  assert.throws(() => repo.void(sale.number, reason), /void failure/);
  assert.deepEqual(readSnapshot(db, 'a'), memory);
  db.exec('DROP TRIGGER reject_void');
  assert.deepEqual(repo.void(sale.number, reason), voidInvoice(store, sale.number, reason, now));
  assert.deepEqual(readSnapshot(db, 'a'), memory);
  assert.throws(() => repo.void(sale.number, { ...reason, version: repo.get(sale.number).version }), /already been voided/);
  repo.delete(sale.number); memory = deleteInvoice(memory, sale.number);
  assert.deepEqual(readSnapshot(db, 'a'), memory);
  db.exec("CREATE TRIGGER reject_delete BEFORE DELETE ON documents WHEN OLD.collection='invoice-records' BEGIN SELECT RAISE(ABORT,'delete failure'); END;");
  assert.throws(() => repo.delete(pending.number), /delete failure/);
  assert.deepEqual(readSnapshot(db, 'a'), memory);
  db.exec('DROP TRIGGER reject_delete');
  repo.delete(pending.number); memory = deleteInvoice(memory, pending.number);
  assert.deepEqual(readSnapshot(db, 'a'), memory);
  assert.equal(memory['stock-list'][0].qty, 10);
  assert.equal(memory['stock-list'][0].net, 90);
  assert.equal(memory['invoice-counter'], 3);
  db.close(); db = openDatabase(file, key);
  assert.deepEqual(readSnapshot(db, 'a'), memory);
});
