'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { randomBytes, randomUUID } = require('node:crypto');
const { openDatabase: openOperationalDatabase } = require('../lib/database/database');
const openDatabase = (file, key) => openOperationalDatabase(file, key, { create: !fs.existsSync(file) });
const { importSnapshot, readSnapshot } = require('../lib/database/snapshot-migration');
const { InvoiceRepository } = require('../lib/database/invoice-repository');
const { createInvoice } = require('../lib/services/invoice-creation');

test('row invoice creation preserves financial parity, replay, pending orders and atomic stock/counter/receipts', t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'vj-invoice-repo-'));
  const key = randomBytes(32), file = path.join(directory, 'invoices.db');
  let db = openDatabase(file, key);
  t.after(() => { if (db.open) db.close(); key.fill(0); fs.rmSync(directory, { recursive: true, force: true }); });
  let memory = { 'stock-list': [{ id: 'ring', item: 'Gold Ring', purity: '22K', qty: 10, gross: 100, net: 90 }, { id: 'unrelated', item: 'Silver', purity: 'Silver', qty: 1, gross: 1, net: 1 }], 'invoice-records': [], 'old-gold-records': [], 'purchase-records': [], 'payment-records': [], 'invoice-counter': 1 };
  importSnapshot(db, memory, { storeId: 'a', sourceSha256: 'a'.repeat(64), acknowledgeLegacy: true });
  const now = () => new Date('2026-10-28T08:00:00Z');
  const repository = new InvoiceRepository(db, 'a', { now });
  const store = { read: () => structuredClone(memory), write: data => { memory = structuredClone(data); } };
  const input = { requestId: randomUUID(), number: 'VJ000001', status: 'completed', customer: 'Synthetic invoice', invoiceDate: '2026-10-28', items: [{ stockId: 'ring', name: 'Gold Ring', purity: '22K', gross: 10, net: 9, pcs: 4, rate: 1000, making: 0 }], exchanges: [{ metal: 'gold', weight: .1, rate: 1000 }], manualDiscount: 20, gstRate: 3, paid: 1000, expectedTotal: 9150 };
  assert.deepEqual(repository.create(input).record, createInvoice(store, input, now).record);
  assert.deepEqual(readSnapshot(db, 'a'), memory);
  assert.equal(memory['stock-list'][0].qty, 6); assert.equal(memory['stock-list'][0].net, 81);
  const before = readSnapshot(db, 'a');
  assert.equal(repository.create(input).replayed, true);
  assert.deepEqual(readSnapshot(db, 'a'), before);
  assert.throws(() => repository.create({ ...input, paid: 1001 }), /already used/);
  assert.throws(() => repository.create({ ...input, requestId: randomUUID() }), /already saved/);
  assert.throws(() => repository.create({ ...input, number: 'VJ000002', requestId: randomUUID(), items: [{ ...input.items[0], pcs: 99 }] }), /Not enough/);
  const next = { ...input, number: 'VJ000002', requestId: randomUUID() };
  db.exec("CREATE TRIGGER fail_invoice_receipt BEFORE INSERT ON documents WHEN NEW.collection='old-gold-records' BEGIN SELECT RAISE(ABORT,'receipt failure'); END;");
  assert.throws(() => repository.create(next), /receipt failure/);
  assert.deepEqual(readSnapshot(db, 'a'), before);
  db.exec('DROP TRIGGER fail_invoice_receipt');
  const pending = { ...next, status: 'pending', gstRate: 0, exchanges: [], manualDiscount: 0, expectedTotal: 9000 };
  assert.deepEqual(repository.create(pending).record, createInvoice(store, pending, now).record);
  assert.deepEqual(readSnapshot(db, 'a'), memory);
  assert.equal(memory['stock-list'][0].qty, 6);
  assert.equal(memory['invoice-counter'], 3);
  const nonGst = { ...pending, number: 'VJ000003', requestId: randomUUID(), status: 'completed', items: [{ ...input.items[0], pcs: 2, gross: 5, net: 4 }], paid: 5000, expectedTotal: 4000 };
  assert.deepEqual(repository.create(nonGst).record, createInvoice(store, nonGst, now).record);
  assert.deepEqual(readSnapshot(db, 'a'), memory);
  assert.equal(memory['invoice-records'][0].due, 0);
  assert.equal(memory['invoice-records'][0].paid, 5000);
  assert.equal(memory['stock-list'][0].qty, 4);
  assert.equal(memory['stock-list'][0].net, 77);
  assert.equal(memory['invoice-counter'], 4);
  const plan = db.prepare("EXPLAIN QUERY PLAN SELECT payload FROM documents WHERE store_id=? AND collection='invoice-records' AND json_extract(payload,'$.creationRequestId')=?").all('a', input.requestId).map(row => row.detail).join(' ');
  assert.match(plan, /SEARCH.*invoice_request_lookup/);
  db.close(); db = openDatabase(file, key);
  assert.deepEqual(readSnapshot(db, 'a'), memory);
});
