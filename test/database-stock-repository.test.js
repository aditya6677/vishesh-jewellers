'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { randomBytes } = require('node:crypto');
const { openDatabase: openOperationalDatabase } = require('../lib/database/database');
const openDatabase = (file, key) => openOperationalDatabase(file, key, { create: !fs.existsSync(file) });
const { importSnapshot } = require('../lib/database/snapshot-migration');
const { StockRepository } = require('../lib/database/stock-repository');
const { CompatibilityStore } = require('../lib/database/compatibility-store');
const { StockService } = require('../lib/services/stock-service');

test('row-level stock operations match existing rules, paginate in SQL and invalidate stale snapshots', t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'vj-stock-repo-'));
  const db = openDatabase(path.join(directory, 'stock.db'), randomBytes(32));
  t.after(() => { db.close(); fs.rmSync(directory, { recursive: true, force: true }); });
  const snapshot = { 'stock-list': [], 'invoice-records': [], 'old-gold-records': [], 'purchase-records': [], 'payment-records': [], 'invoice-counter': 1 };
  importSnapshot(db, snapshot, { storeId: 'a', sourceSha256: 'a'.repeat(64), acknowledgeLegacy: true });
  let seq = 0;
  const now = () => new Date('2026-10-28T08:00:00Z');
  const repository = new StockRepository(db, 'a', { now, id: () => 'item-' + ++seq });
  let memory = structuredClone(snapshot), memorySeq = 0;
  const legacy = new StockService({ read: () => structuredClone(memory), write: value => { memory = structuredClone(value); } }, { now, id: () => 'item-' + ++memorySeq });
  const compatibility = new CompatibilityStore(db, 'a'), stale = compatibility.read();
  for (let i = 0; i < 25; i++) {
    const input = { item: 'Ring ' + i, purity: i % 2 ? 'Silver' : '22K', qty: 10, gross: 100, net: 90 };
    repository.create(input); legacy.create(input);
  }
  assert.throws(() => compatibility.write(stale), /changed/);
  assert.equal(repository.page().items.length, 10);
  let cursor = null, items = [];
  do { const page = repository.page({ cursor, limit: 7 }); items.push(...page.items); cursor = page.next; } while (cursor !== null);
  assert.deepEqual(items, legacy.list().items);
  const saved = repository.get('item-1');
  const batch = { qty: 5, gross: 200, net: 200, version: saved.version };
  repository.mutate('item-1', batch, 'batch'); legacy.mutate('item-1', batch, 'batch');
  assert.deepEqual(repository.get('item-1').item, legacy.list().items[0]);
  assert.equal(repository.get('item-1').item.qty, 15);
  assert.equal(repository.get('item-1').item.gross, 300);
  const edit = { item: 'Edited Ring', purity: '22K', qty: 15, gross: 300, net: 290, version: repository.get('item-1').version };
  repository.mutate('item-1', edit, 'edit'); legacy.mutate('item-1', edit, 'edit');
  assert.deepEqual(repository.get('item-1').item, legacy.list().items[0]);
  importSnapshot(db, snapshot, { storeId: 'b', sourceSha256: 'b'.repeat(64), acknowledgeLegacy: true });
  assert.throws(() => new StockRepository(db, 'b').get('item-1'), error => error.statusCode === 404);
  assert.throws(() => repository.mutate('item-1', batch, 'delete'), error => error.statusCode === 409);
  const fresh = repository.get('item-1');
  assert.throws(() => repository.mutate('item-1', { ...batch, version: fresh.version, net: 500 }, 'edit'));
  assert.deepEqual(repository.get('item-1'), fresh);
  repository.mutate('item-1', { version: fresh.version }, 'delete');
  assert.throws(() => repository.get('item-1'), error => error.statusCode === 404);
  assert.throws(() => repository.page({ limit: 101 }), /Page size/);
  const plan = db.prepare('EXPLAIN QUERY PLAN SELECT ordinal,payload FROM documents WHERE store_id=? AND collection=? AND ordinal>? ORDER BY ordinal LIMIT 11').all('a', 'stock-list', 10).map(row => row.detail).join(' ');
  assert.match(plan, /SEARCH.*store_id=.*collection=.*ordinal>/);
  assert.doesNotMatch(plan, /TEMP B-TREE/);
  db.exec("CREATE TRIGGER fail_stock BEFORE INSERT ON documents WHEN NEW.identity='item-26' BEGIN SELECT RAISE(ABORT,'synthetic failure'); END;");
  const revision = db.prepare('SELECT revision FROM store_revisions WHERE store_id=?').get('a').revision;
  assert.throws(() => repository.create({ item: 'Fail', purity: '22K', qty: 1, gross: 1, net: 1 }), /synthetic failure/);
  assert.equal(db.prepare('SELECT revision FROM store_revisions WHERE store_id=?').get('a').revision, revision);
});
