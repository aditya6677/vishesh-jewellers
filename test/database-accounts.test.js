'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { randomBytes } = require('node:crypto');
const { openDatabase } = require('../lib/database/database');
const { importSnapshot, readSnapshot } = require('../lib/database/snapshot-migration');
const { AsyncAccounts } = require('../lib/security/async-accounts');
const { createSqlAccountRepository } = require('../lib/security/sql-account-repository');
const { BusinessPermission, validatePermissions } = require('../lib/security/business-permissions');
const { createDatabaseBackup } = require('../lib/database/backup');

test('encrypted SQL accounts isolate credentials, revoke sessions and preserve business records', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'vj-sql-accounts-'));
  const file = path.join(directory, 'store.db'), key = randomBytes(32);
  const db = openDatabase(file, key, { create: true });
  let accounts;
  t.after(async () => { await accounts?.close(); if (db.open) db.close(); key.fill(0); fs.rmSync(directory, { recursive: true, force: true }); });
  const original = { 'stock-list': [], 'invoice-records': [], 'purchase-records': [], 'payment-records': [], 'old-gold-records': [], 'invoice-counter': 1 };
  importSnapshot(db, original, { storeId: 'main', sourceSha256: 'a'.repeat(64), acknowledgeLegacy: true });
  accounts = new AsyncAccounts(file, key, 'main');
  const root = await accounts.call('setup', { username: 'superadmin', name: 'Test administrator', password: 'Disposable administrator password!' });
  assert.equal(root.role, 'superadmin'); assert.equal(root.credential, undefined);
  await assert.rejects(accounts.call('setup', { username: 'another', name: 'Another', password: 'Another disposable password!' }), /already configured/);
  const login = await accounts.call('login', { username: 'superadmin', password: 'Disposable administrator password!' });
  const staff = await accounts.call('createUser', login.token, { username: 'staff', name: 'Staff test', role: 'staff', password: 'Temporary disposable password!' });
  const staffLogin = await accounts.call('login', { username: 'staff', password: 'Temporary disposable password!' });
  await assert.rejects(accounts.call('current', staffLogin.token), /temporary password/);
  await accounts.call('changePassword', staffLogin.token, 'Temporary disposable password!', 'Replacement disposable password!');
  await assert.rejects(accounts.call('current', staffLogin.token), /Sign in/);
  const signedIn = await accounts.call('login', { username: 'staff', password: 'Replacement disposable password!' });
  await assert.rejects(accounts.call('createUser', signedIn.token, { username: 'intruder', name: 'Intruder', role: 'superadmin', password: 'A disposable intruder password!' }), /Access denied/);
  await accounts.call('setAccess', login.token, staff.id, { role: 'staff', active: false });
  await assert.rejects(accounts.call('current', signedIn.token), /Sign in/);
  await assert.rejects(accounts.call('setAccess', login.token, root.id, { role: 'staff', active: false }), /at least one/);
  const repository = createSqlAccountRepository(db, 'main');
  assert.ok(repository.permissions('superadmin').includes(BusinessPermission.SETTINGS_RESTORE));
  assert.ok(!repository.permissions('staff').includes(BusinessPermission.INVOICES_DELETE));
  assert.throws(() => validatePermissions(['unknown.permission']));
  assert.deepEqual(readSnapshot(db, 'main'), original);
  assert.equal(JSON.stringify(readSnapshot(db, 'main')).includes('scrypt'), false);
  assert.ok(db.prepare('SELECT count(*) AS count FROM account_audit').get().count >= 3);
  await accounts.close(); accounts = undefined;
  const backup = path.join(directory, 'accounts-backup.db');
  createDatabaseBackup(db, key, backup);
  const recovered = openDatabase(backup, key, { readonly: true });
  try {
    assert.deepEqual(recovered.prepare('SELECT * FROM account_users ORDER BY id').all(), db.prepare('SELECT * FROM account_users ORDER BY id').all());
    assert.deepEqual(recovered.prepare('SELECT * FROM account_roles ORDER BY role_id').all(), db.prepare('SELECT * FROM account_roles ORDER BY role_id').all());
    assert.deepEqual(readSnapshot(recovered, 'main'), original);
  } finally { recovered.close(); }
  accounts = new AsyncAccounts(file, key, 'main');
  await assert.rejects(accounts.call('current', login.token), /Sign in/);
  assert.equal((await accounts.call('login', { username: 'superadmin', password: 'Disposable administrator password!' })).user.id, root.id);
  for (let i = 0; i < 5; i++) await assert.rejects(accounts.call('login', { username: 'staff', password: 'Incorrect disposable password!' }), /Incorrect/);
  await accounts.close(); accounts = new AsyncAccounts(file, key, 'main');
  await assert.rejects(accounts.call('login', { username: 'staff', password: 'Replacement disposable password!' }), /Too many attempts/);
});
