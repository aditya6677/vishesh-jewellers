'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { randomBytes, randomUUID } = require('node:crypto');
const { openDatabase: openOperationalDatabase } = require('../lib/database/database');
const openDatabase = (file, key) => openOperationalDatabase(file, key, { create: !fs.existsSync(file) });
const { importSnapshot } = require('../lib/database/snapshot-migration');
const { CompatibilityStore } = require('../lib/database/compatibility-store');
const { createJsonStore } = require('../lib/json-store');
const { StockService } = require('../lib/services/stock-service');
const { TransactionService } = require('../lib/services/transaction-service');
const { InvoiceService } = require('../lib/services/invoice-service');
const { RecordService } = require('../lib/services/record-service');
const { DashboardService } = require('../lib/services/dashboard-service');
const initial = () => ({ 'stock-list': [], 'invoice-records': [], 'old-gold-records': [], 'purchase-records': [], 'payment-records': [], 'invoice-counter': 1 });

function lifecycle(store) {
  let sequence = 0;
  const dependencies = { now: () => new Date('2026-10-28T08:00:00Z'), id: () => 'test-' + ++sequence };
  const stocks = new StockService(store, dependencies), trades = new TransactionService(store, dependencies);
  const invoices = new InvoiceService(store), records = new RecordService(store, dependencies);
  const run = operation => store.execute ? store.execute(operation) : operation();
  run(() => stocks.create({ item: 'Gold Ring', purity: '22K', qty: 10, gross: 100, net: 90 }));
  const stockId = stocks.list().items[0].id;
  run(() => trades.save('purchases', { metal: 'gold', weight: 10, rate: 1000 }));
  run(() => trades.save('payments', { type: 'metal', metal: 'gold', weight: 2, purity: 40 }));
  run(() => trades.save('payments', { type: 'amount', amount: 100 }));
  run(() => trades.save('payments', { type: 'self-expense', amount: 50 }));
  const line = { stockId, name: 'Gold Ring', purity: '22K', gross: 10, net: 9, pcs: 4, rate: 1000, making: 0 };
  const input = { requestId: randomUUID(), number: 'VJ000001', status: 'completed', customer: 'Synthetic parity', invoiceDate: '2026-10-28', items: [line], exchanges: [{ metal: 'gold', weight: .1, rate: 1000 }], manualDiscount: 20, gstRate: 3, paid: 1000, expectedTotal: 9150 };
  const sale = run(() => invoices.create(input));
  assert.equal(sale.record.due, 8150);
  assert.equal(run(() => invoices.create(input)).replayed, true);
  assert.equal(stocks.list().items[0].qty, 6);
  run(() => records.settle('VJ000001', { version: records.get('VJ000001').version, method: 'silver', weight: 2, rate: 50 }));
  const edit = run(() => invoices.edit('VJ000001', { version: records.get('VJ000001').version, customer: 'Synthetic parity', invoiceDate: '2026-10-28', items: [{ ...line, gross: 20, net: 18, pcs: 5 }], exchanges: [{ metal: 'gold', weight: .2, rate: 1000 }], manualDiscount: 40, gstRate: 3, paid: 1500, expectedTotal: 18300 }));
  assert.equal(edit.record.paid, 1600); assert.equal(edit.record.due, 16700);
  const before = store.read();
  assert.throws(() => run(() => records.settle('VJ000001', { version: records.get('VJ000001').version, method: 'amount', amount: 999999 })), /valid settlement/);
  assert.deepEqual(store.read(), before);
  const summary = new DashboardService(store).snapshot();
  const saleStock = stocks.list().items;
  run(() => invoices.void('VJ000001', { version: records.get('VJ000001').version, reason: 'Synthetic parity cancellation' }));
  assert.equal(stocks.list().items[0].qty, 10);
  assert.equal(records.get('VJ000001').record.due, 0);
  run(() => invoices.delete('VJ000001'));
  const metalPayment = trades.list('payments').items.find(item => item.type === 'metal');
  run(() => trades.save('payments', { version: trades.list('payments').versions[metalPayment.id] }, metalPayment.id, true));
  const purchase = trades.list('purchases').items[0];
  run(() => trades.save('purchases', { version: trades.list('purchases').versions[purchase.id], metal: 'gold', weight: 12, rate: 1000 }, purchase.id));
  assert.equal(trades.list('purchases').balances.gold, 12);
  run(() => trades.save('purchases', { version: trades.list('purchases').versions[purchase.id] }, purchase.id, true));
  assert.deepEqual(store.read()['old-gold-records'], []);
  return { summary, stock: saleStock, invoice: { paid: edit.record.paid, due: edit.record.due, total: edit.record.total }, counter: store.read()['invoice-counter'], finalSummary: new DashboardService(store).snapshot() };
}

test('existing business services retain JSON financial results on encrypted database adapter', t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'vj-service-parity-'));
  const file = path.join(directory, 'service.db'), key = randomBytes(32);
  let db = openDatabase(file, key);
  t.after(() => { if (db.open) db.close(); key.fill(0); fs.rmSync(directory, { recursive: true, force: true }); });
  const json = createJsonStore(path.join(directory, 'store.json'), { encryptionKey: randomBytes(32).toString('base64') }); json.write(initial());
  importSnapshot(db, initial(), { storeId: 'parity', sourceSha256: 'a'.repeat(64), acknowledgeLegacy: true });
  const sql = new CompatibilityStore(db, 'parity');
  assert.deepEqual(lifecycle(sql), lifecycle(json));
  const other = new CompatibilityStore(db, 'parity');
  const stale = other.read(), fresh = sql.read(); fresh['invoice-counter'] = 3; sql.write(fresh);
  assert.throws(() => other.write(stale), /changed/);
  assert.equal(sql.read()['invoice-counter'], 3);
  const preserved = sql.read();
  db.exec("CREATE TRIGGER fail_service_write BEFORE INSERT ON documents BEGIN SELECT RAISE(ABORT,'synthetic disk failure'); END;");
  assert.throws(() => sql.execute(() => { const snapshot = sql.read(); snapshot['invoice-counter'] = 4; sql.write(snapshot); }), /synthetic disk failure/);
  assert.deepEqual(sql.read(), preserved);
  db.close(); db = openDatabase(file, key);
  assert.deepEqual(new CompatibilityStore(db, 'parity').read(), preserved);
});
