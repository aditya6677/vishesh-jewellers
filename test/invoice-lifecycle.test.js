'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { randomBytes, randomUUID } = require('node:crypto');
const { createJsonStore } = require('../lib/json-store');
const { InvoiceService } = require('../lib/services/invoice-service');
const { RecordService } = require('../lib/services/record-service');
const { calculateDashboard } = require('../lib/dashboard-summary');

test('encrypted sale-settlement-edit-void-reload lifecycle retains exact financial and inventory balances', t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'vj-lifecycle-'));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));
  const file = path.join(directory, 'store.json'), encryptionKey = randomBytes(32).toString('base64');
  const store = createJsonStore(file, { encryptionKey });
  const stock = [{ id: 'ring', item: 'Gold Ring', purity: '22K', qty: 10, gross: 100, net: 90 }];
  store.write({ 'stock-list': stock, 'invoice-records': [], 'old-gold-records': [], 'invoice-counter': 1 });
  const invoices = new InvoiceService(store), records = new RecordService(store);
  const line = { stockId: 'ring', name: 'Gold Ring', purity: '22K', gross: 10, net: 9, pcs: 4, rate: 1000, making: 0 };
  const created = invoices.create({ requestId: randomUUID(), number: 'VJ000001', status: 'completed', customer: 'Lifecycle Test Only', invoiceDate: '2026-10-26', items: [line], exchanges: [{ metal: 'gold', weight: .1, rate: 1000 }], manualDiscount: 20, gstRate: 3, paid: 1000, expectedTotal: 9150 });
  assert.equal(created.record.due, 8150);
  assert.deepEqual(store.read()['stock-list'][0], { ...stock[0], qty: 6, gross: 90, net: 81 });
  const settled = records.settle('VJ000001', { version: records.get('VJ000001').version, method: 'silver', weight: 2, rate: 50 });
  assert.equal(settled.record.paid, 1100); assert.equal(settled.record.due, 8050);
  const edited = invoices.edit('VJ000001', { version: settled.version, customer: 'Lifecycle Test Only', invoiceDate: '2026-10-27', items: [{ ...line, gross: 20, net: 18, pcs: 5 }], exchanges: [{ metal: 'gold', weight: .2, rate: 1000 }], manualDiscount: 40, gstRate: 3, paid: 1500, expectedTotal: 18300 });
  assert.equal(edited.record.paid, 1600); assert.equal(edited.record.due, 16700);
  assert.deepEqual(store.read()['stock-list'][0], { ...stock[0], qty: 5, gross: 80, net: 72 });
  const beforeVoid = store.read();
  const summary = calculateDashboard(beforeVoid['invoice-records'], [], [], beforeVoid['old-gold-records']);
  assert.equal(summary.sales, 18300); assert.equal(summary.collected, 1500);
  assert.equal(summary.gold.balance, .2); assert.equal(summary.silver.balance, 2);
  const voided = invoices.void('VJ000001', { version: edited.version, reason: 'Lifecycle test cancellation' });
  assert.equal(voided.record.paid, 1600); assert.equal(voided.record.due, 0);
  const final = store.read(); assert.deepEqual(final['stock-list'], stock); assert.equal(final['invoice-counter'], 2);
  const totals = calculateDashboard(final['invoice-records'], [], [], final['old-gold-records']);
  for (const field of ['sales', 'collected', 'due', 'invoices']) assert.equal(totals[field], 0);
  assert.equal(totals.gold.balance, 0); assert.equal(totals.silver.balance, 0);
  assert.deepEqual(createJsonStore(file, { encryptionKey }).read(), final);
  assert.ok(!fs.readFileSync(file, 'utf8').includes('Lifecycle Test Only'));
  invoices.delete('VJ000001');
  assert.deepEqual(store.read()['stock-list'], stock);
  assert.deepEqual(store.read()['invoice-records'], []); assert.deepEqual(store.read()['old-gold-records'], []);
});
