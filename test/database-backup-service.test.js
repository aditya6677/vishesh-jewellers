'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { randomBytes } = require('node:crypto');
const { openDatabase } = require('../lib/database/database');
const { importSnapshot, readSnapshot } = require('../lib/database/snapshot-migration');
const { DatabaseBackupService } = require('../lib/database/backup-service');

test('database backup service schedules same-key weekly copies and verifies portable recovery without activation', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'vj-backup-service-'));
  const key = randomBytes(32), file = path.join(directory, 'store.db');
  const db = openDatabase(file, key, { create: true });
  t.after(() => { if (db.open) db.close(); key.fill(0); fs.rmSync(directory, { recursive: true, force: true }); });
  importSnapshot(db, { 'invoice-counter': 16 }, { storeId: 'main', sourceSha256: 'a'.repeat(64), acknowledgeLegacy: true });
  let date = new Date('2026-12-31T12:00:00Z');
  const service = new DatabaseBackupService(db, key, { databaseFile: file, backupDir: path.join(directory, 'backups') }, { now: () => date });
  service.createWeekly(); service.createWeekly();
  assert.equal(service.status().backups.length, 1);
  date = new Date('2027-01-01T12:00:00Z'); service.createWeekly();
  assert.equal(service.status().backups.length, 1);
  date = new Date('2027-01-05T12:00:00Z'); service.createWeekly();
  assert.equal(service.status().backups.length, 2);
  const original = readSnapshot(db, 'main');
  const running = service.createPortable('Disposable service recovery phrase!');
  await assert.rejects(service.createPortable('Disposable service recovery phrase!'), /already running/);
  const result = await running;
  assert.equal(result.verified, true);
  const name = path.basename(result.path);
  assert.equal((await service.verifyPortable(name, 'Disposable service recovery phrase!')).verified, true);
  assert.deepEqual(readSnapshot(db, 'main'), original);
  assert.equal(fs.readdirSync(service.directory).some(name => name.startsWith('.verify-')), false);
  await assert.rejects(service.verifyPortable(name, 'Incorrect service phrase!'), /Recovery failed/);
  assert.equal(fs.readdirSync(service.directory).some(name => name.startsWith('.verify-')), false);
  await assert.rejects(service.verifyPortable('../store.db', 'Disposable service recovery phrase!'), /Select/);
  assert.equal(service.status().weekly, 'same-key');
  const previous = service.directory;
  await assert.rejects(service.changeLocation('relative-folder'), /absolute/);
  assert.equal(service.directory, previous);
  const destination = path.join(directory, 'chosen-backups'); fs.mkdirSync(destination);
  await service.changeLocation(destination);
  assert.equal(fs.existsSync(path.join(previous, name)), true);
  assert.equal(service.status().backups.length, 0);
  service.createWeekly();
  assert.equal(service.status().backups.length, 1);
  const reopened = new DatabaseBackupService(db, key, { databaseFile: file, backupDir: path.join(directory, 'backups') });
  assert.equal(reopened.directory, service.directory);
  assert.deepEqual(readSnapshot(db, 'main'), original);
  assert.equal(service.status().recovery, 'verify-only');
});
