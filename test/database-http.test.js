'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { once } = require('node:events');
const { randomBytes, randomUUID } = require('node:crypto');
const { openDatabase } = require('../lib/database/database');
const { importSnapshot } = require('../lib/database/snapshot-migration');
const { createConfig } = require('../lib/config');
const { createApplication } = require('../lib/app');

test('SQLite HTTP/React path has bounded pages, filters, transactional mutations and streaming exports', async t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'vj-sqlite-http-'));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));
  const key = randomBytes(32), file = path.join(directory, 'store.db');
  const db = openDatabase(file, key, { create: true });
  const snapshot = {
    'stock-list': Array.from({ length: 25 }, (_, i) => ({ id: 'stock-' + i, item: 'Ring ' + i, purity: i % 2 ? 'Silver' : '22K', qty: 100, gross: 100, net: 100 })),
    'invoice-records': Array.from({ length: 25 }, (_, i) => ({ number: 'VJ' + String(i + 1).padStart(6, '0'), customer: i ? 'Customer ' + i : '=DANGER', mobile: '900000' + String(i).padStart(4, '0'), invoiceDate: '2026-10-27', savedAt: '2026-10-27T08:00:00Z', status: 'completed', weightMode: 'line-total', total: '₹100.00', paid: 0, due: 100, payments: [], soldItems: [] })),
    'purchase-records': [], 'payment-records': [], 'old-gold-records': [], 'invoice-counter': 26, 'business-info': { name: 'Synthetic' }
  };
  importSnapshot(db, snapshot, { storeId: 'main', sourceSha256: 'a'.repeat(64), acknowledgeLegacy: true }); db.close();
  const config = createConfig({ DATA_BACKEND: 'sqlite', DATABASE_FILE: file, DATABASE_KEY: key.toString('base64'), DATA_DIR: path.join(directory, 'json-never-used'), BACKUP_DIR: path.join(directory, 'backups'), BACKEND_MODE: process.env.BACKEND_MODE, PORT: '0' });
  const errors = [];
  const app = createApplication({ config, desktop: { enabled: false }, logger: { error: (...args) => errors.push(args) } });
  t.after(async () => { app.server.closeAllConnections(); await app.close(); key.fill(0); });
  await app.initialize(); app.server.listen(0, '127.0.0.1'); await once(app.server, 'listening');
  const base = 'http://127.0.0.1:' + app.server.address().port;
  const request = (url, method = 'GET', body) => fetch(base + url, { method, headers: { 'content-type': 'application/json' }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
  const first = await (await request('/api/stocks')).json();
  assert.equal(first.items.length, 10); assert.equal(first.pagination.total, 25);
  const second = await (await request('/api/stocks?page=2')).json();
  assert.equal(second.items[0].id, 'stock-10');
  const search = await (await request('/api/stocks?query=Ring%2024')).json();
  assert.equal(search.items[0].id, 'stock-24');
  const records = await (await request('/api/records?status=due&q=Customer%2020')).json();
  assert.equal(records.items.length, 1); assert.equal(records.items[0].number, 'VJ000021');
  assert.equal((await request('/api/stocks?pageSize=999')).status, 400);
  assert.equal((await request('/api/records?from=2026-99-99')).status, 400);
  assert.equal((await request('/api/records?q=' + 'x'.repeat(257))).status, 400);
  assert.equal((await request('/api/storage/stock-list', 'PUT', { value: '[]' })).status, 400);
  const sale = { requestId: randomUUID(), number: 'VJ000026', status: 'completed', customer: 'HTTP sale', invoiceDate: '2026-10-28', items: [{ stockId: 'stock-0', name: 'Ring 0', purity: '22K', gross: 1, net: 1, pcs: 4, rate: 100, making: 0 }], exchanges: [], manualDiscount: 0, gstRate: 3, paid: 50, expectedTotal: 103 };
  const saved = await request('/api/invoices', 'POST', sale);
  assert.equal(saved.status, 200); const invoice = await saved.json();
  assert.equal(invoice.record.due, 53); assert.equal(invoice.stockScope, 'affected-only');
  assert.equal(JSON.parse((await (await request('/api/storage/invoice-counter')).json()).value), 27);
  assert.equal((await (await request('/api/stocks/stock-0')).json()).item.qty, 96);
  assert.equal((await (await request('/api/invoices', 'POST', sale)).json()).replayed, true);
  const retrieved = await (await request('/api/records/VJ000026')).json();
  const settled = await request('/api/records/VJ000026/settlements', 'POST', { version: retrieved.version, fullyPaid: true });
  assert.equal(settled.status, 200);
  assert.equal((await settled.json()).record.due, 0);
  const csv = await request('/api/reports/records.csv?from=2026-10-27&to=2026-10-27');
  assert.equal(csv.status, 200); const text = await csv.text();
  assert.match(text, /'=DANGER/); assert.match(text, /VJ000025/); assert.doesNotMatch(text, /VJ000026/);
  const snapshotCsv = await request('/api/reports/dashboard.csv?from=2026-10-28&to=2026-10-28');
  assert.equal(snapshotCsv.status, 200); assert.match(await snapshotCsv.text(), /summary.afterPayment/);
  assert.equal((await request('/api/backup/download')).status, 500);
  const backupStatus = await (await request('/api/backup-status')).json();
  assert.equal(backupStatus.backend, 'sqlite');
  assert.equal(backupStatus.backups.filter(row => !row.portable).length, 1);
  assert.equal((await request('/api/database-backup/portable', 'POST', { passphrase: '5512' })).status, 400);
  const portable = await request('/api/database-backup/portable', 'POST', { passphrase: 'Disposable HTTP recovery phrase!' });
  assert.equal(portable.status, 200);
  const portableResult = await portable.json(); assert.equal(portableResult.verified, true);
  const backupName = (await (await request('/api/backup-status')).json()).backups.find(row => row.portable).name;
  const verify = await request('/api/database-backup/verify', 'POST', { name: backupName, passphrase: 'Disposable HTTP recovery phrase!' });
  assert.equal(verify.status, 200); assert.equal((await verify.json()).verified, true);
  assert.equal((await request('/api/database-backup/verify', 'POST', { name: '../store.db', passphrase: 'Disposable HTTP recovery phrase!' })).status, 400);
  assert.equal((await request('/api/database-backup/verify', 'POST', { name: backupName, passphrase: 'This password is wrong!' })).status, 400);
  const foreign = await fetch(base + '/api/database-backup/portable', { method: 'POST', headers: { 'content-type': 'application/json', origin: 'https://untrusted.example' }, body: JSON.stringify({ passphrase: 'Disposable HTTP recovery phrase!' }) });
  assert.equal(foreign.status, 400);
  assert.equal((await (await request('/api/records/VJ000026')).json()).record.due, 0);
  const files = { database: fs.readFileSync(path.join(portableResult.path, 'database.db')).toString('base64'), manifest: fs.readFileSync(path.join(portableResult.path, 'manifest.json'), 'utf8'), recovery: fs.readFileSync(path.join(portableResult.path, 'recovery.json'), 'utf8') };
  const imported = await request('/api/database-backup/import', 'POST', { files, passphrase: 'Disposable HTTP recovery phrase!' });
  assert.equal(imported.status, 200);
  const importedName = (await imported.json()).name;
  const prepared = await (await request('/api/database-backup/prepare', 'POST', { name: importedName, passphrase: 'Disposable HTTP recovery phrase!' })).json();
  assert.equal((await request('/api/database-backup/activate', 'POST', { token: prepared.token, confirmation: 'no' })).status, 400);
  const restored = await request('/api/database-backup/activate', 'POST', { token: prepared.token, confirmation: 'RESTORE' });
  assert.equal(restored.status, 200); assert.equal((await restored.json()).restored, true);
  assert.equal((await request('/api/dashboard')).status, 200);
  assert.equal((await (await request('/api/records/VJ000026')).json()).record.due, 0);
  assert.equal((await request('/api/backup/restore', 'POST', {})).status, 409);
  assert.equal(fs.existsSync(config.dataFile), false);
  assert.equal((await (await request('/api/version')).json()).dataBackend, 'sqlite');
  const html = await (await request('/')).text(); assert.match(html, /window.vjDatabaseMode=true/);
  assert.equal((await request('/?frontend=legacy')).status, 409);
  assert.equal(errors.filter(args => !['Invalid page','valid date range','Search text is too long'].some(message => String(args).includes(message))).length, 0);
});
