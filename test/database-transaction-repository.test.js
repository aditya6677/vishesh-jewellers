'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { randomBytes } = require('node:crypto');
const { openDatabase: openOperationalDatabase } = require('../lib/database/database');
const openDatabase = (file, key) => openOperationalDatabase(file, key, { create: !fs.existsSync(file) });
const { importSnapshot, readSnapshot } = require('../lib/database/snapshot-migration');
const { TransactionRepository } = require('../lib/database/transaction-repository');
const { TransactionService } = require('../lib/services/transaction-service');

test('purchase/payment row mutations preserve service calculations, ledger guards and rollback', t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'vj-trade-repo-'));
  const key = randomBytes(32), file = path.join(directory, 'trades.db');
  let db = openDatabase(file, key);
  t.after(() => { if (db.open) db.close(); key.fill(0); fs.rmSync(directory, { recursive: true, force: true }); });
  let memory = { 'stock-list': [], 'invoice-records': [], 'old-gold-records': [], 'purchase-records': [], 'payment-records': [] };
  importSnapshot(db, memory, { storeId: 'a', sourceSha256: 'a'.repeat(64) });
  importSnapshot(db, memory, { storeId: 'b', sourceSha256: 'b'.repeat(64) });
  const now = () => new Date('2026-10-28T08:00:00Z');
  let sqlId = 0, jsonId = 0;
  const repo = new TransactionRepository(db, 'a', { now, id: () => 'trade-' + ++sqlId });
  const legacy = new TransactionService({ read: () => structuredClone(memory), write: data => { memory = structuredClone(data); } }, { now, id: () => 'trade-' + ++jsonId });
  const save = (kind, input, id, deleting = false) => {
    const result = repo.save(kind, input, id, deleting);
    const original = legacy.save(kind, input, id, deleting);
    assert.deepEqual(result.items, original.items); assert.deepEqual(result.balances, original.balances);
    assert.deepEqual(readSnapshot(db, 'a'), memory);
    return result;
  };
  save('purchases', { metal: 'gold', weight: 10, rate: 1000 });
  save('payments', { type: 'metal', metal: 'gold', weight: 2, purity: 40, reason: 'Party' });
  assert.equal(repo.get('payments', 'trade-2').item.fineWeight, .8);
  assert.equal(Object.hasOwn(repo.get('payments', 'trade-2').item, 'amount'), false);
  assert.throws(() => new TransactionRepository(db, 'b').get('payments', 'trade-2'), error => error.statusCode === 404);
  const before = readSnapshot(db, 'a');
  assert.throws(() => repo.save('purchases', { version: repo.get('purchases', 'trade-1').version }, 'trade-1', true), /insufficient old/);
  assert.deepEqual(readSnapshot(db, 'a'), before);
  const stale = repo.get('payments', 'trade-2').version;
  save('payments', { type: 'amount', amount: 200, version: stale }, 'trade-2');
  assert.equal(Object.hasOwn(repo.get('payments', 'trade-2').item, 'fineWeight'), false);
  assert.throws(() => repo.save('payments', { type: 'amount', amount: 201, version: stale }, 'trade-2'), /changed/);
  save('payments', { type: 'metal', metal: 'gold', weight: 2, purity: 40, version: repo.get('payments', 'trade-2').version }, 'trade-2');
  db.exec("CREATE TRIGGER fail_trade_receipt BEFORE INSERT ON documents WHEN NEW.collection='old-gold-records' BEGIN SELECT RAISE(ABORT,'receipt failure'); END;");
  const intact = readSnapshot(db, 'a');
  assert.throws(() => repo.save('purchases', { metal: 'gold', weight: 12, rate: 1000, version: repo.get('purchases', 'trade-1').version }, 'trade-1'), /receipt failure/);
  assert.deepEqual(readSnapshot(db, 'a'), intact);
  db.exec('DROP TRIGGER fail_trade_receipt');
  save('payments', { version: repo.get('payments', 'trade-2').version }, 'trade-2', true);
  save('purchases', { version: repo.get('purchases', 'trade-1').version }, 'trade-1', true);
  save('payments', { type: 'self-expense', amount: 50, reason: 'Test' });
  assert.equal(repo.page('payments', { limit: 1 }).items.length, 1);
  save('payments', { type: 'self-expense', amount: 60, reason: 'Edited', version: repo.get('payments', 'trade-3').version }, 'trade-3');
  save('payments', { version: repo.get('payments', 'trade-3').version }, 'trade-3', true);
  assert.equal(repo.page('purchases').items.length, 0);
  save('purchases', { metal: 'silver', weight: 100, rate: 80 });
  save('payments', { type: 'metal', metal: 'silver', weight: 40, purity: 50 });
  assert.equal(repo.get('payments', 'trade-5').item.fineWeight, 20);
  const silverEdit = save('purchases', { metal: 'silver', weight: 150, rate: 80, version: repo.get('purchases', 'trade-4').version }, 'trade-4');
  assert.equal(silverEdit.balances.silver, 110);
  assert.equal(repo.get('purchases', 'trade-4').item.amount, 12000);
  assert.throws(() => repo.save('payments', {}, undefined, true), /Select an entry/);
  db.close(); db = openDatabase(file, key);
  assert.deepEqual(readSnapshot(db, 'a'), memory);
});
