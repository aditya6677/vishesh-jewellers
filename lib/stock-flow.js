function applyWeightOnlyStockFlow(html) {
  const stockOptions = [
    'function stockOptionsHtml(selectedId, rowId, searchTerm=""){',
    '  const search = String(searchTerm).trim().toLowerCase();',
    "  const opts = ['<option value=\"\">— select a stock item —</option>'];",
    '  stockList.forEach(s=>{',
    '    const remainingNet = parseFloat(s.net)||0;',
    '    const remainingGross = parseFloat(s.gross)||0;',
    '    const available = availableQtyFor(s, rowId);',
    '    if((available <= 0 || (remainingNet <= 0 && remainingGross <= 0)) && s.id !== selectedId) return;',
    '    const searchable = `${s.item} ${s.purity} ${s.id} ${available} ${s.gross} ${s.net}`.toLowerCase();',
    '    if(search && !searchable.includes(search) && s.id !== selectedId) return;',
    '    opts.push(`<option value="${s.id}" ${s.id===selectedId?\'selected\':\'\'}>${escapeHtml(s.item)} · ${s.purity} · ${available} pcs · ${fmtWt(s.net)}g remaining</option>`);',
    '  });',
    "  return opts.join('');",
    '}',
    ''
  ].join('\n');
  const completeSale = [
    "document.getElementById('btnCompleteSale').addEventListener('click', async ()=>{",
    '  if(saleCompleted) return;',
    "  const customerInput = document.getElementById('cust-name');",
    "  if(!customerInput.value.trim()){ toast('Customer name is required'); customerInput.focus(); return; }",
    "  const invoiceDateInput = document.getElementById('inv-date');",
    "  if(!invoiceDateInput.value){ toast('Invoice date is required'); invoiceDateInput.focus(); return; }",
    "  if(rows.some(r => !r.stockId)){ toast('Select a stock item for every invoice row'); const row = rows.find(r => !r.stockId); const element = Array.from(document.querySelectorAll('#itemsTbody tr')).find(item => item.dataset.id === row.id); if(element) element.querySelector('.f-stock').focus(); return; }",
    '  const linkedRows = rows.filter(r => r.stockId);',
    '  if(!linkedRows.length){',
    "    toast('Add at least one item from stock');",
    '    return;',
    '  }',
    '  for(const row of linkedRows){',
    '    const rowElement = Array.from(document.querySelectorAll("#itemsTbody tr")).find(element => element.dataset.id === row.id);',
    '    if(!Number.isInteger(Number(row.pcs)) || Number(row.pcs) < 1){',
    "      toast('Quantity (Pcs) is required and must be at least 1');",
    "      if(rowElement) rowElement.querySelector('.f-pcs').focus();",
    '      return;',
    '    }',
    '    if(!(parseFloat(row.gross) > 0)){',
    "      toast('Gross Wt (g) is required for every invoice item');",
    "      if(rowElement) rowElement.querySelector('.f-gross').focus();",
    '      return;',
    '    }',
    '    if(!(parseFloat(row.net) > 0)){',
    "      toast('Net Wt (g) is required for every invoice item');",
    "      if(rowElement) rowElement.querySelector('.f-net').focus();",
    '      return;',
    '    }',
    '    if(parseFloat(row.net) > parseFloat(row.gross)){',
    "      toast('Net weight cannot be greater than gross weight');",
    "      if(rowElement) rowElement.querySelector('.f-net').focus();",
    '      return;',
    '    }',
    '    if(!(parseFloat(row.rate) > 0)){',
    "      toast('Rate per gram is required for every invoice item');",
    "      if(rowElement) rowElement.querySelector('.f-rate').focus();",
    '      return;',
    '    }',
    '  }',
    '  const incompleteExchange = Array.from(document.querySelectorAll("#exchangeRows .exchange-row")).find(exchangeRow => {',
    '    const weight = Number(exchangeRow.querySelector(".exchange-row-weight").value) || 0;',
    '    const rate = Number(exchangeRow.querySelector(".exchange-row-rate").value) || 0;',
    '    return exchangeRow.dataset.required === "true" || ((weight > 0 || rate > 0) && (!(weight > 0) || !(rate > 0)));',
    '  });',
    '  if(incompleteExchange){',
    "    toast('Complete both weight and rate for each exchange item, or remove the empty row');",
    '    const weightInput = incompleteExchange.querySelector(".exchange-row-weight");',
    '    const rateInput = incompleteExchange.querySelector(".exchange-row-rate");',
    '    (Number(weightInput.value) > 0 ? rateInput : weightInput).focus();',
    '    return;',
    '  }',
    "  const discountInput = document.getElementById('invoice-discount');",
    "  const amountPaidInput = document.getElementById('amount-paid');",
    "  if(discountInput && Number(discountInput.value) < 0){ toast('Discount cannot be negative'); discountInput.focus(); return; }",
    "  if(amountPaidInput && Number(amountPaidInput.value) < 0){ toast('Amount paid cannot be negative'); amountPaidInput.focus(); return; }",
    '  const requested = new Map();',
    '  linkedRows.forEach(r=>{',
    '    const current = requested.get(r.stockId) || { gross:0, net:0, pcs:0, name:r.name };',
    '    const pcs = Number(r.pcs);',
    '    current.pcs += pcs;',
    '    current.gross += parseFloat(r.gross)||0;',
    '    current.net += parseFloat(r.net)||0;',
    '    requested.set(r.stockId, current);',
    '  });',
    '  for(const [stockId, requestedWeight] of requested){',
    '    const stock = stockList.find(x=>x.id===stockId);',
    '    if(!stock || requestedWeight.pcs > (parseInt(stock.qty)||0) || requestedWeight.gross > (parseFloat(stock.gross)||0) + 0.0001 || requestedWeight.net > (parseFloat(stock.net)||0) + 0.0001){',
    "      toast('Not enough remaining quantity or weight for \"' + requestedWeight.name + '\"');",
    '      return;',
    '    }',
    '  }',
    '  requested.forEach((requestedWeight, stockId)=>{',
    '    const stock = stockList.find(x=>x.id===stockId);',
    '    stock.qty = Math.max((parseInt(stock.qty)||0) - requestedWeight.pcs, 0);',
    '    stock.gross = Math.max((parseFloat(stock.gross)||0) - requestedWeight.gross, 0);',
    '    stock.net = Math.max((parseFloat(stock.net)||0) - requestedWeight.net, 0);',
    '  });',
    "  await storeSet('stock-list', stockList);",
    '  renderStockTable(); renderStockStats();',
    '  saleCompleted = true;',
    '  setSaleStatus();',
    "  toast('Stock quantity and weight updated — sale recorded');",
    '});',
    '',
    "document.getElementById('btnPrint')"
  ].join('\n');
  const renderStockStats = [
    'function renderStockStats(){',
    "  const goldStock = stockList.filter(stock => stock.purity !== 'Silver');",
    "  const silverStock = stockList.filter(stock => stock.purity === 'Silver');",
    '  const updateCard = (valueId, label, entries) => {',
    '    const gross = entries.reduce((sum, entry) => sum + (parseFloat(entry.gross)||0), 0);',
    '    const net = entries.reduce((sum, entry) => sum + (parseFloat(entry.net)||0), 0);',
    '    const value = document.getElementById(valueId);',
    '    value.previousElementSibling.textContent = label;',
    "    value.classList.add('stock-summary');",
    "    value.innerHTML = '<div class=\"stock-weight-pair\"><div class=\"stock-weight-item\"><span>Gross</span><strong>' + fmtWt(gross) + ' g</strong></div><div class=\"stock-weight-item\"><span>Net</span><strong>' + fmtWt(net) + ' g</strong></div></div><small class=\"stock-entry-count\">' + entries.length + ' ' + (entries.length === 1 ? 'item' : 'items') + '</small>';",
    '  };',
    "  updateCard('stat-count', 'Gold Stock', goldStock);",
    "  updateCard('stat-weight', 'Silver Stock', silverStock);",
    '}',
    '',
    'function renderStockTable()'
  ].join('\n');

  return html
    .replace(/function stockOptionsHtml\(selectedId, rowId(?:, searchTerm=['"]{2})?\)\{[\s\S]*?\n\}/, stockOptions)
    .replace('class="f-stock">', 'class="f-stock" required>')
    .replace('class="f-name" value="${escapeHtml(r.name)}" placeholder="Item name">', 'class="f-name" value="${escapeHtml(r.name)}" placeholder="Select from stock" readonly>')
    .replace('class="f-hsn" value="${escapeHtml(r.hsn)}" style="width:56px;">', 'class="f-hsn" value="${escapeHtml(r.hsn)}" style="width:56px;" readonly>')
    .replace(/\$\{r\.stockId\?'readonly':''\}/g, '')
    .replace('<select class="f-purity">', '<select class="f-purity" ${r.stockId?\'disabled\':\'\'}>')
    .replace("tr.querySelector('.f-gross').addEventListener('input', e=>{ row.gross = e.target.value; renderRowsTable(); renderPreview(); });", "tr.querySelector('.f-gross').addEventListener('input', e=>{ row.gross = e.target.value; tr.querySelector('.amount-cell').textContent = '₹'+fmt(rowAmount(row)); renderPreview(); });")
    .replace("tr.querySelector('.f-net').addEventListener('input', e=>{ row.net = e.target.value; renderRowsTable(); renderPreview(); });", "tr.querySelector('.f-net').addEventListener('input', e=>{ row.net = e.target.value; tr.querySelector('.amount-cell').textContent = '₹'+fmt(rowAmount(row)); renderPreview(); });")
    .replace("tr.querySelector('.f-rate').addEventListener('input', e=>{ row.rate = e.target.value; renderRowsTable(); renderPreview(); });", "tr.querySelector('.f-rate').addEventListener('input', e=>{ row.rate = e.target.value; tr.querySelector('.amount-cell').textContent = '₹'+fmt(rowAmount(row)); renderPreview(); });")
    .replace("tr.querySelector('.f-making').addEventListener('input', e=>{ row.making = e.target.value; renderRowsTable(); renderPreview(); });", "tr.querySelector('.f-making').addEventListener('input', e=>{ row.making = e.target.value; tr.querySelector('.amount-cell').textContent = '₹'+fmt(rowAmount(row)); renderPreview(); });")
    .replace(/function renderStockStats\(\)\{[\s\S]*?\n\}\n\nfunction renderStockTable\(\)/, renderStockStats)
    .replace(/document\.getElementById\('btnCompleteSale'\)\.addEventListener\('click', async \(\)=>\{[\s\S]*?\n\}\);\n\ndocument\.getElementById\('btnPrint'\)/, completeSale);
}

module.exports = { applyWeightOnlyStockFlow };
